    "    grafico: barras_medias",
    "    notas:",
    "      - \"Pensado para variables numéricas (montos, tiempos, edades, etc.).\"",
    "",
    "    filas:",
    "      - id: grupo_1",
    "        label: \"Grupo 1\"",
    "        grupos:",
    "          valor: { vars: [ingreso_grupo1] }",
    "      - id: grupo_2",
    "        label: \"Grupo 2\"",
    "        grupos:",
    "          valor: { vars: [ingreso_grupo2] }",
    "",
    "    columnas:",
    "      - id: n_dato",
    "        label: \"N con dato\"",
    "        tipo: conteo_cond",
    "        var: \"@valor\"",
    "        condicion: \"no_es_na\"   # helper: x no es NA",
    "",
    "      - id: media",
    "        label: \"Media\"",
    "        tipo: media",
    "        var: \"@valor\"",
    "        condicion: \"no_es_na\"",
    "",
    "      - id: mediana",
    "        label: \"Mediana\"",
    "        tipo: mediana",
    "        var: \"@valor\"",
