    "      - id: pct_cero",
    "        label: \"% con valor 0\"",
    "        tipo: proporcion_rel",
    "        numerador: n_cero",
    "        denominador: n_dato",
    "",
    "",
    "  # ===========================================================",
    "  # EJEMPLO 7: tabla_compuesta usando banderas precomputadas",
