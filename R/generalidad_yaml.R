    "  #",
    "  - id: IND7",
    "    nombre_corto: \"banderas_precomputadas\"",
    "    titulo: \"Ejemplo de uso de variables bandera calculadas en R\"",
    "    tipo: tabla_compuesta",
    "    grafico: barras_agrupadas",
    "    notas:",
    "      - \"Las banderas BOOLEANAS (TRUE/FALSE) se calculan previamente en R y se guardan en rp_data.\"",
    "      - \"Por ejemplo: rp_data$flag_condicion_a <- rp_data$var_x == 1 & rp_data$var_y == 2\"",
    "",
    "    filas:",
    "      - id: flag_a",
